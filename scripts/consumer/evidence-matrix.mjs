#!/usr/bin/env node
/**
 * Generates docs/releases/0.17-evidence-matrix.md from docs/api/volt-parity.md and
 * consumer/evidence-map.json, and FAILS if the two disagree:
 *   - every V/C/P row must have a map entry whose spec file exists and contains every listed test
 *     title (so a renamed/removed test cannot silently leave a row "covered");
 *   - every route in a map entry must be rendered by the SSR and hydration specs;
 *   - N rows are not mapped to runtime tests: their documented native/composition justification is
 *     copied instead.
 * Usage: node scripts/consumer/evidence-matrix.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const parity = readFileSync(join(ROOT, 'docs/api/volt-parity.md'), 'utf8');
const map = JSON.parse(readFileSync(join(ROOT, 'consumer/evidence-map.json'), 'utf8'));
const out = join(ROOT, 'docs/releases/0.17-evidence-matrix.md');

const rows = [
  ...parity.matchAll(/^### `([^`]+)`[^\n]*\(\*\*([A-Z])\*\*\)\n([\s\S]*?)(?=^### `|^## )/gm),
].map((m) => ({
  name: m[1],
  cls: m[2],
  body: m[3],
}));
const problems = [];
if (rows.length !== 46) problems.push(`expected 46 inventory rows, found ${rows.length}`);

const specRoutes = (file) =>
  [...readFileSync(join(ROOT, 'consumer/e2e', file), 'utf8').matchAll(/'\/(\w+)'/g)].map(
    (m) => m[1],
  );
const routed = new Set(
  [...specRoutes('ssr.spec.ts')].filter((r) => specRoutes('hydration.spec.ts').includes(r)),
);

const lines = [];
for (const row of rows) {
  const quartz = /\*\*Quartz equivalent:\*\*\s*([^\n]+)/.exec(row.body)?.[1] ?? '';
  if (row.cls === 'N') {
    lines.push(
      `| \`${row.name}\` | N | — | — | — | — | — | native / composition: ${quartz.replace(/\|/g, '\\|').slice(0, 140)} |`,
    );
    continue;
  }
  const entry = map[row.name];
  if (!entry) {
    problems.push(`${row.name} (${row.cls}): no consumer evidence entry`);
    lines.push(`| \`${row.name}\` | ${row.cls} | **none** | — | — | — | — | NOT COVERED |`);
    continue;
  }
  const specPath = join(ROOT, 'consumer/e2e', entry.spec);
  if (!existsSync(specPath)) problems.push(`${row.name}: spec ${entry.spec} missing`);
  else {
    const text = readFileSync(specPath, 'utf8');
    for (const title of entry.titles)
      if (!text.includes(title))
        problems.push(`${row.name}: test "${title}" not found in ${entry.spec}`);
  }
  if (!routed.has(entry.page))
    problems.push(
      `${row.name}: page /${entry.page} is not covered by BOTH ssr.spec.ts and hydration.spec.ts`,
    );
  lines.push(
    `| \`${row.name}\` | ${row.cls} | \`/${entry.page}\` | \`${entry.spec}\` (${entry.titles.length}) | yes | yes | yes | ${entry.a11y ? 'axe + keyboard' : 'keyboard only'} |`,
  );
}

const vcp = rows.filter((r) => r.cls !== 'N');
const header = `# 0.17 consumer evidence matrix

Generated by \`node scripts/consumer/evidence-matrix.mjs\` from \`docs/api/volt-parity.md\` and \`consumer/evidence-map.json\` (do not edit by hand). The script fails when a V/C/P row has no consumer test, a listed test title no longer exists, or a page is not rendered by both the SSR and the hydration specs.

**What "covered" means.** Each row below is exercised by the installed-tarball consumer app (\`consumer/app\`, Angular standalone, zoneless, strict templates, production AOT) in the three Playwright engines: server-rendered by the real Angular SSR server (\`consumer/e2e/ssr.spec.ts\`), hydrated without errors, replaced nodes or id drift (\`consumer/e2e/hydration.spec.ts\`), and driven through real keyboard/pointer input (the listed spec). Results per Angular version are in \`docs/releases/0.17-acceptance.md\`. N rows have no Quartz runtime and are therefore not mapped to runtime tests.

Rows: ${rows.length} total — ${vcp.length} interactive/behavioural (mapped), ${rows.length - vcp.length} native/composition (N).

| Row | Class | Fixture page | Spec (tests) | SSR | Hydration | Interaction | Accessibility |
| --- | --- | --- | --- | --- | --- | --- | --- |
`;
writeFileSync(out, header + lines.join('\n') + '\n');
if (problems.length) {
  console.error('✗ evidence matrix:\n  ' + problems.join('\n  '));
  process.exit(1);
}
console.log(`✓ evidence matrix: ${vcp.length} mapped rows, ${rows.length - vcp.length} N rows`);
