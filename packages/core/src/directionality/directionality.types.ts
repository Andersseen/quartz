/** Text/layout direction. Mirrors the HTML `dir` attribute's two real values. */
export type Direction = 'ltr' | 'rtl';

/** A logical position along the inline (reading) axis. */
export type LogicalInlineDirection = 'inline-start' | 'inline-end';

/** A physical horizontal side. */
export type PhysicalHorizontal = 'left' | 'right';

/** The two arrow keys that move along the horizontal/inline axis. */
export type InlineArrowKey = 'ArrowLeft' | 'ArrowRight';
